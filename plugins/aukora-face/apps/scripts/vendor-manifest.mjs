#!/usr/bin/env node
/*
 * The provenance manifest for the carried vendor tree: every file that ships
 * with this face, by size and digest, plus where each source came from.
 *
 * `pnpm vendor:manifest` rewrites it; `pnpm vendor:check` fails when the tree
 * and the record have drifted. Both scripts named this path in package.json
 * before the file itself was carried over from the Deep-era package, so the
 * guard threw MODULE_NOT_FOUND instead of checking anything.
 */
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const VENDOR_ROOT = join(PACKAGE_ROOT, 'vendor')
const MANIFEST_PATH = join(VENDOR_ROOT, 'manifest.json')
const OMIT = new Set(['README.md', 'manifest.json'])
// GENERATED BYTES ARE NAMED BY SHAPE, NOT BY ADDRESS. The voice sidecar is
// carried twice — the copy the host runs and the copy it came from — and an
// earlier revision of this rule named only the first one's directories. A
// second copy's weights would then have been manifested and carried, which is
// the one thing this file exists to prevent. So the rule matches any `.venv`
// or `__pycache__` segment anywhere in the vendor tree, and any `voice/models`
// directory, wherever a copy of the sidecar puts it.
const GENERATED_SEGMENTS = new Set(['.venv', '__pycache__'])

/** A whole directory of generated bytes: never descended into. */
function omittedDirectory(path) {
  return path.split('/').some(part => GENERATED_SEGMENTS.has(part))
}

/**
 * One generated file. **`voice/models` IS NOW OMITTED WHOLE, CARVE-OUT AND ALL.**
 *
 * **THIS FUNCTION USED TO DESCEND `voice/models` AND SPARE ONE NAME — `PROMPT_NAME`, "the clone
 * prompt lives in it".** *aura-83's egress audit found that carve-out and the materializer's
 * `voice/models` copy as the same defect in two places:* **a directory the audit calls generated bytes
 * cannot also be a directory the manifest reaches into for one authored file**, *because the exception is
 * what keeps the whole directory reachable* -- *a sidecar that drops a second prompt, a model index or a
 * downloaded voice beside `aurora-prompt.wav` is then covered by a rule that no longer excludes the path
 * it sits in.*
 *
 * **AND THE PROMPT ITSELF IS NOT AT RISK.** *It is an authored file, so it belongs where authored files
 * live and are tracked* -- *not inside a directory whose stated purpose is bytes the manifest refuses to
 * carry.* **The exception was doing the opposite of what its comment claimed**: *it was not protecting the
 * prompt, it was keeping the generated directory in scope.*
 *
 * *`PROMPT_NAME` is removed rather than left unused*, **so a future reader cannot reintroduce the carve-out
 * by finding the constant already defined and assuming it is load-bearing.**
 */
function omittedGeneratedPath(path) {
  const parts = path.split('/')
  if (parts.some(part => GENERATED_SEGMENTS.has(part))) return true
  for (let index = 0; index + 1 < parts.length - 1; index += 1) {
    if (parts[index] === 'voice' && parts[index + 1] === 'models') return true
  }
  return false
}

async function pathsBelow(root) {
  const output = []
  const visit = async (directory) => {
    const entries = await readdir(directory, { withFileTypes: true })
    entries.sort((left, right) => left.name.localeCompare(right.name, 'en'))
    for (const entry of entries) {
      const absolute = join(directory, entry.name)
      const path = relative(root, absolute).split('\\').join('/')
      if (entry.isDirectory()) {
        if (omittedDirectory(path)) continue
        await visit(absolute)
      }
      else if (omittedGeneratedPath(path)) continue
      else if (entry.isFile()) output.push(absolute)
      else throw new Error(`vendor tree contains unsupported entry: ${absolute}`)
    }
  }
  await visit(root)
  return output
}

async function makeManifest() {
  const files = {}
  for (const absolute of await pathsBelow(VENDOR_ROOT)) {
    const path = relative(VENDOR_ROOT, absolute).split('\\').join('/')
    if (OMIT.has(path) || omittedGeneratedPath(path)) continue
    const bytes = await readFile(absolute)
    files[path] = {
      bytes: bytes.length,
      sha256: createHash('sha256').update(bytes).digest('hex'),
    }
  }
  return {
    schemaVersion: 1,
    sources: {
      three: {
        repository: 'https://github.com/mrdoob/three.js',
        pin: 'r180',
        version: '0.180.0',
        license: 'MIT',
        provenance: 'three/upstream-three.json',
        runtimeEntry: 'three/three.module.min.js',
      },
      dakiniCode: {
        repository: 'aumara-xyz/dakini-code',
        commit: '1fc98117a9a6234e1179bc7c5084a58ade378963',
        buildCommand: 'npm ci && npm run build:app',
        runtimeEntry: 'dakini-code/index.html',
      },
      zetaHarp: {
        repository: 'aumara-xyz/zeta-harp',
        commit: 'aa1100fa56e2a86ccd181cb39d13122e62abdf9f',
        tree: '8c2f47d67479c19ce98e0c8d57916fd6d86feb34',
        runtimeEntry: 'zeta-harp/index.html',
      },
      aumaLingwa: {
        repositoryRevision: 'b413a89b109900a9037a9ed725b0d1b474e4f550',
        runtimeEntry: 'auma-lingwa/runtime/auma-lingwa.html',
      },
      aumaLive: {
        repositoryRevision: 'b413a89b109900a9037a9ed725b0d1b474e4f550',
        license: 'AGPL-3.0-or-later',
        runtimeEntry: 'auma-live/runtime/auma-live.html',
      },
    },
    files,
  }
}

const rendered = `${JSON.stringify(await makeManifest(), null, 2)}\n`
if (process.argv.includes('--check')) {
  const current = await readFile(MANIFEST_PATH, 'utf8')
  if (current !== rendered) throw new Error('vendor/manifest.json is stale; run pnpm vendor:manifest')
} else {
  await writeFile(MANIFEST_PATH, rendered)
}
