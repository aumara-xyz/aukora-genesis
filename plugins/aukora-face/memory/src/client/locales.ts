/**
 * **THE DECLARED KEY TYPE, WITHOUT WHICH THE NAMESPACE CANNOT BE REGISTERED.**
 *
 * `ctx.locale.register(NS, …)` types its first argument from `LocaleNamespaceMap`, and a face declares itself there
 * with `declare module`. **That declaration needs a type to point at**, and `aumlok` has `AumlokKey` for exactly this
 * purpose while `memory` had none — which is why `'"memory"' is not assignable to parameter of type 'key…'`.
 */
export type MemoryKey = keyof typeof zh
