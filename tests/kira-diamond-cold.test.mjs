/** Extract the framed JSON report, or fail: no block means no verdict was produced. */
function reportOf(stdout) {
  const begin = stdout.indexOf('REPORT-JSON-BEGIN')
  const end = stdout.indexOf('REPORT-JSON-END')
  assert.ok(begin >= 0 && end > begin, 'the consumer printed no framed REPORT-JSON block')
  return JSON.parse(stdout.slice(begin + 'REPORT-JSON-BEGIN'.length, end))
}

/** The refusal name the consumer printed, or undefined when it printed none. */
const refusalOf = stdout => (stdout.match(/^VERDICT: (?:REFUSED|UNSUPPORTED) {2}(\S+)$/m) ?? [])[1]

/** Copy one directory tree. Every tamper happens in a copy; the good export is never touched. */
function copyTree(from, to) {
  cpSync(from, to, { recursive: true })
  return to
}

/**
 * A DISPOSABLE COPY OF THE VENDORED DIAMOND WITH ONE CEILING REMOVED, for C3's mutation.
 *
 * `vendor/` is READ here and never written: the copy goes under the caller's `work`, only the copy is edited, and the removal is
 * ASSERTED to have matched — a mutation that silently removed nothing would leave the arm passing while claiming it broke something,
 * which is the defect family this court lives inside.
 *
 * @param {string} to - the disposable directory to build.
 * @returns {string} the copy's root, to hand `--package-root`.
 */
function vendoredCopyWithoutReplayCeiling(to) {
  copyTree(PACKAGE_ROOT, to)
  const file = join(to, 'diamond', 'kira_evidence.py')
  const source = readFileSync(file, 'utf8')
  const next = source.replace(/\s*"NO_GLOBAL_REPLAY_PREVENTION:[\s\S]*?"for the first time\.",/u, '')
  assert.notEqual(next, source, 'the mutation MUST match the ceiling it removes — a no-op mutation proves nothing')
  writeFileSync(file, next)
  return to
}

/**
 * Flip exactly ONE byte where it matters, keeping the document parseable: a hex character moves to
 * another hex character, any other letter changes case.
 *
 * @param {string} path - the file to edit (always inside a disposable copy).
 * @param {string} needle - the text the byte must follow.
 * @returns {string} a description of the flip, for the evidence line.
 */
function flipOneByte(path, needle) {
  const bytes = readFileSync(path)
  const at = bytes.indexOf(Buffer.from(needle, 'utf8'))
  assert.ok(at >= 0, `${basename(path)} does not contain ${JSON.stringify(needle)}`)
  const index = at + Buffer.byteLength(needle)
  const before = bytes[index]
  const character = String.fromCharCode(before)
  const HEX = '0123456789abcdef'
  bytes[index] = HEX.includes(character)
    ? HEX.charCodeAt((HEX.indexOf(character) + 1) % 16)
    : (before >= 0x41 && before <= 0x5a ? before + 0x20 : before - 0x20)
  assert.notEqual(bytes[index], before, 'a flip must change a byte')
  writeFileSync(path, bytes)
  return `${basename(path)} byte ${index}: ${character} -> ${String.fromCharCode(bytes[index])}`
}

/**
 * The mutations: one check defeated in a DISPOSABLE copy of the vendored consumer, so a tamper arm
 * can be shown to go red. If an arm still passed against a consumer that had stopped making the
 * check it asserts, the arm would be measuring nothing at all. Each edit is asserted to have
 * matched, so a consumer whose text moved fails loudly here instead of silently rubber-stamping.
 *
 * NOTHING UNDER `vendor/` IS EVER WRITTEN: the copy is made under this run's temporary root.
 */
const RUBBER_STAMPS = {
  signature: ['    if len(public_key) != 32 or len(signature) != 64:\n        return False\n',
    '    return True  # RUBBER STAMP: signature verification defeated in a disposable copy\n'],
  identity: ['    return "kira:" + digest.hexdigest()',
    '    return record["recordId"]  # RUBBER STAMP: identity recomputation defeated\n'],
  chain: ['    prev = AURA_RECORD_DOMAIN\n    for index, entry in enumerate(entries[:upto], start=1):\n',
    '    return {"ok": True, "head": entries[upto - 1].get("hash"), "verifiedEntries": min(upto, len(entries))}  # RUBBER STAMP\n'],
  object: ['            raise Refusal("object-tampered", "the object bytes do not hash to the named digest")',
    '            pass  # RUBBER STAMP: object digest check defeated\n'],
  // The small-order rule is the ONLY thing standing between a no-key forgery and a verdict: with it
  // removed, the Ed25519 equation the forgery satisfies holds, and the pre-delta bytes verified it.
  smallOrder: ['    if _scalar_mult(point, 8) == (0, 1):\n        raise Refusal("ed25519-small-order", "small-order points are not accepted")\n',
    '    pass  # RUBBER STAMP: the small-order rule is defeated in a disposable copy\n'],
  // The receipt/Aura digest binding, which the store path used to skip: with it removed, a re-signed
  // `effectDigest` of 0*64 is accepted in BOTH modes — the fail-open this arm exists to catch.
  effectDigest: ['    if receipt["effectDigest"] != content_sha:\n        raise Refusal("effect-digest-mismatch",\n                      "the receipt and its Aura entry name different content digests")\n',
    '    pass  # RUBBER STAMP: the receipt/Aura effect-digest binding is defeated in a disposable copy\n'],
}

/**
 * A disposable copy of `vendor/kira-export` with ONE check defeated.
 * @param {keyof typeof RUBBER_STAMPS} check - which check to defeat.
 * @returns {string} the copy's root, for `--package-root`.
 */
function rubberStampedConsumer(check) {
  const copy = join(work, `consumer-stamped-${check}`)
  cpSync(PACKAGE_ROOT, copy, { recursive: true })
  const target = join(copy, 'diamond/kira_evidence.py')
  const [from, to] = RUBBER_STAMPS[check]
  const text = readFileSync(target, 'utf8')
  assert.ok(text.includes(from), `the rubber stamp for ${check} no longer matches the vendored consumer`)
  writeFileSync(target, text.replace(from, to))
  return copy
}

/**
 * One tampered member, asserted the strongest way available: the run exits 1 with the DEMANDED
 * name, and the same evidence handed back with `--expect <name>` exits 0, which happens only when
 * the observed verdict equals the demanded one.
 *
 * @param {string} name - the refusal name the consumer must produce.
 * @param {string} relative - the exported member to flip a byte in.
 * @param {string} needle - where in that member.
 * @param {{lane?: 'artifact'|'store', consumer?: string}} [options] - which lane reads that member, and which consumer runs.
 * @returns {string} the evidence line.
 */
function tamperArm(name, relative, needle, options = {}) {
  const copy = copyTree(exportDir, join(work, `tamper-${name.replaceAll(/[^a-z0-9]+/giu, '-')}`))
  const flipped = flipOneByte(join(copy, relative), needle)
  const lane = options.lane === 'artifact' ? artifactArgs(copy)
    : options.lane === 'store' ? ['--store', join(copy, 'evidence')] : []
  const consumer = options.consumer === undefined ? CONSUMER : join(options.consumer, 'scripts/verify-kira-evidence.py')
  const packageRoot = options.consumer ?? PACKAGE_ROOT
  const observed = runConsumer([...evidenceArgs(copy, packageRoot), ...lane], emptyDir, consumer)
  assert.equal(observed.status, 1, `expected exit 1 on the tampered member, got ${observed.status}: ${observed.stderr}`)
  assert.equal(refusalOf(observed.stdout), name,
    `expected refusal ${name}, got ${String(refusalOf(observed.stdout))}`)
  const demanded = runConsumer([...evidenceArgs(copy, packageRoot), ...lane, '--expect', name], emptyDir, consumer)
  assert.equal(demanded.status, 0,
    `--expect ${name} did not exit 0, so the observed verdict was not ${name}: ${demanded.stdout.split('\n').slice(-3).join(' | ')}`)
  assert.match(demanded.stdout, new RegExp(`^EXPECTATION: ${name} OBSERVED$`, 'mu'))
  return `${flipped}; refused by name \`${name}\` (exit 1), and \`--expect ${name}\` exits 0`
}

