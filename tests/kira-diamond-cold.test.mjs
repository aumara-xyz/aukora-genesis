/**
 * Forge the exported receipt's signature in a DISPOSABLE copy, using NO PRIVATE KEY.
 *
 * WHAT THE FORGERY IS, and why it is not just a flipped byte. The issuer key is written as the
 * compressed IDENTITY point (y = 1, x = 0) — a point of order 1, for which no private key exists,
 * so no honest signature can ever be produced under it. The signature is the pair `R = S·B`,
 * `s = S` for a scalar the forger simply picks: Ed25519's verification equation `sB = R + kA` then
 * holds for EVERY challenge k, because multiplying the identity point by k yields the identity.
 * The forged bytes are therefore STRUCTURALLY PERFECT — a canonical R, s inside the group order,
 * 64 bytes — and the only thing wrong with them is that the named key is small-order. A consumer
 * that skips the small-order rule verifies this forgery; that is exactly the fail-open the vendored
 * delta closed, and it is why this arm is not the flipped-byte arm above.
 *
 * The arithmetic is the pinned module's own (`diamond.ed25519`), and the measured claims are made
 * here rather than asserted in prose: the identity point is small-order, the equation holds under
 * it in the module's arithmetic AND in the consumer's own (`diamond.kira_evidence`), while the
 * consumer's own strict verifier REFUSES the very signature the equation accepts. A re-pin that
 * moved those names fails loudly here instead of quietly measuring nothing.
 *
 * @param {string} dir - a disposable COPY of the export whose receipt and anchor are rewritten.
 * @returns {{issuerPk: string, anchor: string, receipt: string, sigBytes: number, equationHolds: boolean, consumerEquationHolds: boolean, consumerVerify: boolean, strictRefusal: string}} the forgery, as measured.
 */
function forgeReceiptSignature(dir) {
  const receiptPath = join(dir, 'evidence/receipts', `${STEM}.json`)
  const anchorPath = join(dir, 'forged.anchor')
  const script = String.raw`
import json, sys
from hashlib import sha512
from pathlib import Path
PKG, RECEIPT, ANCHOR = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
sys.path.insert(0, PKG)
from diamond import ed25519 as ed           # the pinned module's own curve arithmetic
from diamond import kira_evidence as ke     # the pinned module's own JCS and verifier

IDENTITY = (0, 1)                           # y = 1: order 1. No private key exists.
S = 4242                                    # the forger's scalar; no key is derived from it
R_POINT = ed._mul(S, ed.B)
R_BYTES = ed._encode_point(R_POINT)
sig = R_BYTES + S.to_bytes(32, "little")
identity_bytes = ed._encode_point(IDENTITY)

receipt = json.loads(RECEIPT.read_text(encoding="utf-8"))
body = {k: v for k, v in receipt.items() if k not in ("sig", "issuerPk")}
message = f"{receipt['kind']}\n".encode("utf-8") + ke.jcs_bytes(body)

challenge = int.from_bytes(sha512(R_BYTES + identity_bytes + message).digest(), "little") % ed.L
consumer_challenge = int.from_bytes(sha512(R_BYTES + identity_bytes + message).digest(), "little") % ke._L
equation_holds = ed._mul(S, ed.B) == ed._add(R_POINT, ed._mul(challenge, IDENTITY))
consumer_equation_holds = (
    ke._compress(ke._scalar_mult(ke._B, S))
    == ke._compress(ke._edwards_add(ke._decompress(R_BYTES),
                                    ke._scalar_mult(IDENTITY, consumer_challenge))))
try:
    ed._decode_point(identity_bytes)
    strict_refusal = None
except ValueError as exc:
    strict_refusal = str(exc)

assert ed._mul(2, IDENTITY) == IDENTITY, "the identity point is not small-order"
assert equation_holds, "the forged signature does not satisfy the verification equation"
assert consumer_equation_holds, "the consumer's own arithmetic rejects the forged equation"
assert strict_refusal and "small-order" in strict_refusal, f"unexpected strict refusal: {strict_refusal!r}"

receipt["issuerPk"] = identity_bytes.hex()
receipt["sig"] = sig.hex()
RECEIPT.write_text(json.dumps(receipt, sort_keys=True), encoding="utf-8")
ANCHOR.write_text(identity_bytes.hex() + "\n", encoding="utf-8")
print(json.dumps({
    "issuerPk": identity_bytes.hex(), "sigBytes": len(sig),
    "equationHolds": equation_holds, "consumerEquationHolds": consumer_equation_holds,
    "consumerVerify": ke.ed25519_verify(identity_bytes, message, sig),
    "strictRefusal": strict_refusal,
}))
`
  const run = spawnSync('python3', ['-c', script, PACKAGE_ROOT, receiptPath, anchorPath],
    { cwd: work, encoding: 'utf8', env: childEnv })
  assert.equal(run.status, 0, `the forgery generator failed: ${run.stderr}`)
  const forged = JSON.parse(run.stdout.trim())
  assert.equal(forged.issuerPk, `01${'00'.repeat(31)}`,
    'the issuer key must be the identity point this court names independently of the generator')
  assert.equal(forged.sigBytes, 64, 'the forgery must be structurally a signature (64 bytes)')
  assert.equal(forged.equationHolds, true, 'the forgery must satisfy the Ed25519 equation under the identity key')
  assert.equal(forged.consumerEquationHolds, true, 'the consumer\'s own arithmetic must accept the forged equation')
  assert.equal(forged.consumerVerify, false, 'the consumer\'s own strict verifier must refuse the forgery')
  assert.match(forged.strictRefusal, /small-order/u, 'the refusal under test must be the small-order rule')
  return { ...forged, receipt: receiptPath, anchor: anchorPath }
}

/**
 * Replace the exported receipt in a DISPOSABLE copy with one RE-SIGNED under a keypair generated in
 * THIS PROCESS, optionally rewriting `effectDigest` to 0*64 first.
 *
 * WHY RE-SIGN AT ALL. `effectDigest` is inside the signed body, so a mutated digest carrying the
 * original signature would be refused as `signature-invalid` and would prove nothing about the
 * digest binding. The mutation is only interesting when the signature over it is VALID — which is
 * why the refusal the arm demands is `effect-digest-mismatch`, a code a broken signature can never
 * produce.
 *
 * WHY A GENERATED KEYPAIR, stated because it is a property and not an implementation detail. The
 * exported receipt is signed by the store's own issuer key and this court does not hold its private
 * half; more to the point, NO FIXTURE MAY CARRY A SECRET KEY INTO THE REPOSITORY. `node:crypto`
 * mints a fresh Ed25519 keypair here per call: the private half lives only in this process's memory,
 * is never returned, never written to the working tree and never written to any temporary directory,
 * and the anchor file holds the PUBLIC half only. Both files this function writes are then CHECKED
 * for the private half's bytes rather than trusted to omit them.
 *
 * @param {string} dir - a disposable COPY of the export whose receipt is replaced.
 * @param {string} stem - the file stem for the anchor this run publishes.
 * @param {boolean} zeroDigest - whether to rewrite `effectDigest` to 0*64 before signing.
 * @returns {{receipt: string, anchor: string, issuerPk: string, effectDigest: string, privateHalfBytes: number, carriesPrivateKey: boolean}} the re-signed pair and what was checked about it.
 */
function resignReceipt(dir, stem, zeroDigest) {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519')
  const issuerPk = publicKey.export({ type: 'spki', format: 'der' }).subarray(-32).toString('hex')
  const receiptPath = join(dir, 'evidence/receipts', `${STEM}.json`)
  const anchorPath = join(dir, `${stem}.anchor`)
  const receipt = JSON.parse(readFileSync(join(exportDir, 'evidence/receipts', `${STEM}.json`), 'utf8'))
  delete receipt.sig
  receipt.issuerPk = issuerPk
  if (zeroDigest) receipt.effectDigest = '0'.repeat(64)
  // The signed body is every field except `sig` and `issuerPk` — the same rule the consumer
  // restates — so the receipt can NAME this key without breaking the signature.
  const body = Object.fromEntries(Object.entries(receipt).filter(([key]) => key !== 'issuerPk'))
  const signedBytes = Buffer.concat([
    Buffer.from(`${receipt.kind}\n`, 'utf8'),
    Buffer.from(canonicalJSON(body), 'utf8'),
  ])
  receipt.sig = signEd25519(null, signedBytes, privateKey).toString('hex')
  assert.equal(receipt.sig.length, 128, 'an Ed25519 signature is 64 bytes of hex')
  writeFileSync(receiptPath, `${JSON.stringify(receipt, null, 2)}\n`)
  writeFileSync(anchorPath, `${issuerPk}\n`)
  // THE SECRET-KEY-FREE PROPERTY, MEASURED: the private half is exported here only to be searched
  // for in the two files just written, and it is never printed or returned.
  const privateHalf = privateKey.export({ type: 'pkcs8', format: 'der' })
  const carriesPrivateKey = readFileSync(receiptPath).includes(privateHalf)
    || readFileSync(anchorPath).includes(privateHalf)
  return {
    receipt: receiptPath, anchor: anchorPath, issuerPk, effectDigest: receipt.effectDigest,
    privateHalfBytes: privateHalf.byteLength, carriesPrivateKey,
  }
}

