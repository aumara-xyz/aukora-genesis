/**
 * Run one named arm. In the main pass a throw is a failure and never stops the suite. With
 * `--mutate` the arm is run a SECOND time with its own invariant broken in a disposable copy, and
 * that run MUST throw — and must throw the arm's own failed assertion, because a harness crash is
 * not a red arm.
 *
 * @param {string} name - the invariant this arm asserts.
 * @param {(broken: boolean) => string} body - returns one evidence line; throws when the invariant does not hold.
 */
function arm(name, body) {
  arms += 1
  let line
  try {
    line = body(false)
    evidence.push(`${String(arms).padStart(2)} ${name}\n     ${line}`)
    process.stdout.write(`  ok    ${name}\n          ${line}\n`)
  } catch (error) {
    failures += 1
    process.stdout.write(`  FAIL  ${name}\n        ${String(error.message).split('\n').join('\n        ')}\n`)
  }
  if (!MUTATE) return
  let red = null
  try {
    body(true)
  } catch (error) {
    red = error
  }
  if (red === null) {
    failures += 1
    process.stdout.write(`  FAIL  ${name} (--mutate)\n        the invariant was broken in a disposable copy and the arm STILL PASSED\n`)
    return
  }
  // *** A MUTANT MUST FAIL FOR THE PROPERTY IT BREAKS (Fable, 2026-09-26). *** The check below used to accept ANY
  // non-zero outcome as a catch, which made the mode vacuous in the way every lane keeps re-finding: a mutant that
  // died on a MISSING MODULE, or that refused without saying why, was counted CAUGHT while proving nothing about the
  // property it was supposed to break. A diagnosis that is empty, that is a traceback, or that is an import failure is
  // reported as CRASH-NOT-A-CATCH AND FAILS THIS COURT — the mutation has to have reached the check.
  const CRASH_OR_SILENT = /ModuleNotFoundError|ERR_MODULE_NOT_FOUND|Cannot find module|ImportError|Traceback \(most recent call last\)|SyntaxError|got -?\d+:\s*$/u
  if (red.name === 'AssertionError' && CRASH_OR_SILENT.test(String(red.message))) {
    failures += 1
    process.stdout.write(`  FAIL  ${name} (--mutate)\n        the broken variant CRASHED, or refused without naming a reason, so it did NOT test the property it breaks:\n        ${String(red.message).split('\n')[0].slice(0, 220)}\n`)
    return
  }
  if (red.name !== 'AssertionError') {
    failures += 1
    process.stdout.write(`  FAIL  ${name} (--mutate)\n        the broken variant CRASHED instead of failing an assertion: ${red.name}: ${red.message}\n`)
    return
  }
  process.stdout.write(`  red   ${name} (--mutate)\n          ${String(red.message).split('\n')[0]}\n`)
}

