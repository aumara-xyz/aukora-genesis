/**
 * THE DIAMOND COLD CONSUMER, RUN FROM A LITERAL EMPTY DIRECTORY, AGAINST A REAL EXPORT.
 *
 *   node tests/kira-diamond-cold.test.mjs            # every arm
 *   node tests/kira-diamond-cold.test.mjs --mutate   # every arm again, its invariant broken
 *
 * WHAT THIS COURT PROVES. `vendor/kira-export/scripts/verify-kira-evidence.py` — the frozen
 * Diamond consumer vendored at upstream pin 7400473825c5af4c17657604bf3d9c3c749ff1a1, whose own
 * docstring says "The consumer must run from an EMPTY directory. Its own package may be reached by
 * an explicit `--package-root`" — is executed with its process cwd set to a directory that holds
 * NOTHING BUT `.` AND `..` (asserted empty by `readdirSync` and by the child's own `os.listdir`),
 * with every input named by ABSOLUTE path from outside that directory, and with `--package-root`
 * as the ONLY route to the `diamond` package (PYTHONPATH is deleted from the child's environment,
 * so an ambient import cannot be what makes it work). Against an export this court builds through
 * the REAL producer path — `createMemoryOwner`, `stageKiraMemoryRecord`, `owner.grantFor`,
 * `owner.settle`, an approval artifact minted by AUMLOK's own `createApprovalReceipt` through
 * `tests/kira-approval-standin.mjs`, and `exportPublicEvidence` — the cold consumer reaches
 * `VERDICT: VERIFIED` with facets 1, 2 and 4 `VERIFIED` and facet 3 `MATCHED`, and, when the
 * caller names the approval lane, reports `APPROVAL_ARTIFACT_VERIFIED` with its operation binding
 * DERIVED from the supplied bytes.
 * The repo's own driver `scripts/kira/verify-public-evidence.py` (another lane's file: this court
 * READS it and never edits it) is run cold from the same empty directory over the same export.
 *
 * IT ALSO PROVES THE CONSUMER CAN GO RED. One flipped byte in each exported member — the receipt's
 * `sig`, the record's `recordId`, the Aura log's entry `hash`, and the object body — is a NAMED
 * refusal from the consumer's own vocabulary (`signature-invalid`, `record-identity-mismatch`,
 * `chain-tampered`, `object-tampered` / `APPROVAL_CONTENT_MISMATCH`), asserted twice: the run must
 * exit 1 with that name, and the SAME evidence handed back with `--expect <that name>` must exit 0,
 * which only happens when the observed verdict equals the demanded one. A disposable copy of the
 * vendored tree with `diamond/` removed fails by name (`SETUP: cannot import diamond.kira_evidence`),
 * and a copy with the consumer script itself removed fails naming the missing file, so this court
 * cannot pass on a missing dependency.
 *
 * TWO OLD FAIL-OPEN PROBES, FOLDED IN AS ARMS. The vendored pin was 12 commits behind Diamond's
 * `0d3cc66`, and the gap carried two live defects that /tmp probes demonstrated before the delta:
 * a signature FORGED WITH NO PRIVATE KEY under a small-order (identity) issuer key made the old
 * bytes answer `VERDICT: VERIFIED`, and a receipt whose `effectDigest` had been rewritten to 0*64
 * and RE-SIGNED was REFUSED without `--store` and VERIFIED with it, so naming MORE evidence
 * weakened the verdict. Both are arms of THIS court now, with no `/tmp` dependency and no fixture
 * that carries a secret key: the forgery is built here from the pinned module's own arithmetic, and
 * the re-signed receipt is signed by an Ed25519 keypair `node:crypto` mints inside this process,
 * whose private half is never serialised (the two files the court writes are checked for it). Each
 * arm carries its own control — the intact bundle verifies FIRST under the same consumer, and the
 * digest arm keeps the honest bundle verifying in BOTH store modes — so neither arm can pass by
 * refusing everything, and the second cannot pass by over-refusing.
 *
 * WHAT IT EXPLICITLY DOES NOT PROVE. The consumer prints its own ceilings and this court asserts
 * they are printed rather than pretending otherwise:
 *
 *   NO_CELL_EXECUTION_PROOF — "receipt verification checks signed bytes, not which program produced
 *     them." `CELL_EXECUTION: NOT_ESTABLISHED` is asserted, never upgraded.
 *   NO_LATESTNESS / COMPLETENESS: UNDETERMINED — a verified position shows the log CONTAINS that
 *     entry; it never shows the log is the tip of the world. This court asserts `NO_LATESTNESS`
 *     and `UNDETERMINED` verbatim.
 *   NO_HUMAN_ATTENDANCE / REPORTED_NOT_PROVEN_ATTENDANCE — `ATTENDANCE: reported-not-proven`. The
 *     approval lane proves a KEY signed bytes; nothing here shows a person was present. The
 *     approver is `tests/kira-approval-standin.mjs`, a daemon-free TEST DOUBLE, and — as that file
 *     says of itself — it imports the digest rule from the consuming lane, so a drift in that rule
 *     would move producer and verifier together and THIS COURT CANNOT SEE IT.
 *   NO_ABSENCE_OF_FORKS, NO_GLOBAL_REPLAY_PREVENTION, NO_WRITE_CLAIM, SAME_UID_ISSUER: the issuer
 *     key is generated by the disposable store under test and published with the evidence, so the
 *     anchor proves a pointer to that key and nothing about who held it.
 *   EVIDENCE_NEVER_AUTHORIZES. A verified record and receipt authorize nothing.
 *
 * It also does NOT prove the exporter's allowlist, determinism or refusals (that is
 * `tests/public-evidence.test.mjs`), and it does NOT prove the release's vendored copy: the
 * consumer under test is this checkout's `vendor/kira-export`, named by absolute path.
 *
 * DISPOSABLE STATE ONLY. One temporary root per run, removed afterwards. Every tampered document
 * and every broken dependency lives in a COPY under that root; the working tree, the release, the
 * live Kira store and `vendor/` are read and never written.
 */
